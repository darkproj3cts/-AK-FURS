#!/usr/bin/env python3
"""
Генератор синтетических данных для проверки solve.py на «новых» числах.
Запуск: python tests/generate_test_data.py [директория]
По умолчанию создаёт test_data/ в корне проекта.

Ожидаемые ответы:
  Q1: unique_orders=8, unique_lines=10
  Q2a: [3, 9]
  Q2b: count=2, sum=37000.00
  Q3: total=5  (Алина Сергеева=3, Вероника Белова=1, Ольга Ершова=1)
  Q4: ["C0001", "C0003", "C0005"]

Логика данных:
  Артикулы:  FUR-A (мин 50000 с 2025-01-01), FUR-B (мин 28000 в 2025, 32000 с 2026),
             FUR-C = новое имя FUR-OLD (мин 20000 с 2025-03-01)
  Нарушения Q3:
    A-001/строка2: FUR-B 27000 < 28000  → Белова
    A-002/строка1: FUR-OLD→FUR-C 18000 < 20000 → Сергеева
    A-002/строка2: FUR-A 52000 - 5% = 49400 < 50000 → Сергеева
    A-005/строка1: FUR-C 19000 < 20000 → Ершова (статус В работе, не Отменён)
    A-008/строка1: FUR-B 26000 < 28000 → Сергеева
  Q2a: A-003 и A-009 — Оплачен, но платежей в банке нет
  Q2b: два неопознанных поступления: 15000 + 22000
  Q4: C0001 и C0003 — invite < price; C0005 — «Запишу вас на встречу» < price
"""

import csv
import os
import sys
import zipfile
from datetime import datetime

import openpyxl

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def write_crm(output_dir):
    header = [
        "Номер заказа", "№ строки", "Дата создания", "Артикул",
        "Менеджер", "Статус", "Цена за ед.", "Кол-во", "Скидка", "Выгружено",
    ]
    rows = [
        # A-001: 2 строки, Оплачен — платёж в банке есть
        # строка 1: OK (55000 >= min 50000)
        # строка 2: нарушение (27000 < min 28000) → Белова
        ["A-00001", "1", "10.05.2025", "FUR-A",   "Белова В.", "Оплачен",   "55 000", "1", "",   "2025-06-01 09:00"],
        ["A-00001", "2", "10.05.2025", "FUR-B",   "Белова В.", "Оплачен",   "27000",  "1", "",   "2025-06-01 09:00"],
        # A-002: 2 строки, Оплачен — платёж в банке есть
        # строка 1: старый артикул FUR-OLD → FUR-C, 18000 < 20000 → нарушение (Сергеева)
        # строка 2: 52000 - 5% = 49400 < 50000 → нарушение (Сергеева)
        ["A-00002", "1", "22.07.2025", "FUR-OLD", "Алина",     "Оплачен",   "18000",  "1", "",   "2025-08-05 10:00"],
        ["A-00002", "2", "22.07.2025", "FUR-A",   "Алина",     "Оплачен",   "52 000", "2", "5%", "2025-08-05 10:00"],
        # A-003: Оплачен, платежа в банке НЕТ → Q2a
        # OK: 33000 >= min 32000 (период FUR-B с 2026-01-01)
        ["A-003",   "1", "2026-02-05", "FUR-B",   "Орлова П.", "Оплачен",   "33,000", "1", "",   "2026-03-01 08:30"],
        # A-004: Отменён → пропускается в Q3
        ["A-004",   "1", "18.09.2025", "FUR-A",   "Ершова О.", "CANCELLED", "45000",  "1", "",   "2025-10-01 11:00"],
        # A-005: В работе; 19000 < min 20000 → нарушение (Ершова)
        ["A-005",   "1", "15.06.2025", "FUR-C",   "Ершова О.", "В работе",  "19000",  "1", "",   "2025-07-01 09:00"],
        # A-007: дублирующий экспорт — берём строку с Выгружено 2025-09-15
        # OK: 50000 >= min 50000 (граница — не нарушение)
        ["A-00007", "1", "10.08.2025", "FUR-A",   "Белова В.", "Оплачен",   "50000",  "1", "",   "2025-09-01 08:00"],
        ["A-00007", "1", "10.08.2025", "FUR-A",   "Белова В.", "Оплачен",   "50000",  "1", "",   "2025-09-15 10:00"],
        # A-008: Оплачен; 26000 < min 28000 → нарушение (Сергеева)
        ["a-8",     "1", "12.03.2025", "FUR-B",   "alina.s",   "PAID",      "26000",  "1", "",   "2025-04-01 09:00"],
        # A-009: Оплачен, платежа в банке НЕТ → Q2a
        ["A-9",     "1", "05.04.2026", "FUR-A",   "Марина",    "Оплачен",   "60000",  "1", "",   "2026-05-01 09:00"],
    ]
    path = os.path.join(output_dir, "01_crm_orders_export.csv")
    with open(path, "w", encoding="utf-8-sig", newline="") as f:
        writer = csv.writer(f, delimiter=";")
        writer.writerow(header)
        for r in rows:
            writer.writerow(r)
    print(f"  [+] {os.path.basename(path)}")


