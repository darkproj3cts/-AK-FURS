def write_xlsx(output_dir):
    wb = openpyxl.Workbook()

    ws_cat = wb.active
    ws_cat.title = "Каталог"
    ws_cat.append(["Артикул", "Наименование", "Тип", "Мех"])
    for row in [
        ("FUR-A",   "Шуба «Классик»",   "Шуба",  "Норка"),
        ("FUR-B",   "Полушубок «Лис»",  "Шуба",  "Лиса"),
        ("FUR-C",   "Жакет «Бобёр»",    "Жакет", "Бобёр"),
        ("FUR-OLD", "Жакет (устар.)",    "Жакет", "Бобёр"),
    ]:
        ws_cat.append(row)

    ws_ren = wb.create_sheet("Переименования")
    ws_ren.append(["Старый артикул", "Новый артикул", "Дата перехода"])
    ws_ren.append(["FUR-OLD", "FUR-C", datetime(2025, 3, 1)])

    ws_price = wb.create_sheet("Прайс_история")
    ws_price.sheet_state = "hidden"
    ws_price.append(["Артикул", "Действует с", "Действует по", "Рекомендованная цена", "Мин. допустимая цена"])
    for row in [
        ("FUR-A", datetime(2025, 1,  1), None,                   60000, 50000),
        ("FUR-B", datetime(2025, 1,  1), datetime(2025, 12, 31), 35000, 28000),
        ("FUR-B", datetime(2026, 1,  1), None,                   38000, 32000),
        ("FUR-C", datetime(2025, 3,  1), None,                   25000, 20000),
    ]:
        ws_price.append(row)

    ws_mgr = wb.create_sheet("Менеджеры")
    ws_mgr.append(["Каноническое имя", "Варианты написания", "Дата выхода", "Дата увольнения"])
    for row in [
        ("Вероника Белова", "Белова В. | вероника | Veronika B | В. Белова",     datetime(2024, 1, 1), None),
        ("Алина Сергеева",  "Сергеева А. | Алина | alina.s | АЛИНА С.",           datetime(2024, 1, 1), None),
        ("Полина Орлова",   "Орлова П. | Полина | P. Orlova | полина орлова",     datetime(2024, 1, 1), datetime(2026, 3, 31)),
        ("Марина Котова",   "Котова М. | Марина | marina_k | М.Котова",            datetime(2025, 6, 2), None),
        ("Ольга Ершова",    "Ершова О. | Ольга | olga.e | О. Ершова",              datetime(2024, 1, 1), None),
    ]:
        ws_mgr.append(row)

    path = os.path.join(output_dir, "03_catalog_prices_reference.xlsx")
    wb.save(path)
    print(f"  [+] {os.path.basename(path)}")


